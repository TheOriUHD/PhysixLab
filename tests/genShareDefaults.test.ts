/**
 * Regenerates src/app/share/defaults.ts (the frozen defaults share links are diffed against, DT-20).
 *   GEN_SHARE_DEFAULTS=1 npx vitest run tests/genShareDefaults.test.ts
 * Re-run it (and commit the result) while share format v2 is unreleased, whenever documents gained fields: the
 * 40 % test in shareLink.test.ts tells you when it is time. After the first public release NEVER regenerate —
 * old links were encoded against exactly the committed values (stale defaults only cost a few bytes).
 */
import { writeFileSync } from 'node:fs';
import { it } from 'vitest';
import { listComponents, makeComponent } from '../src/model/componentRegistry';
import * as f from '../src/model/factory';
import { MATERIAL_PRESETS } from '../src/model/materials';
import { parseDocument, serializeDocument } from '../src/model/serialize';
import type { Entity } from '../src/model/types';

it.skipIf(!process.env.GEN_SHARE_DEFAULTS)('writes src/app/share/defaults.ts', () => {
  const ents: Entity[] = [
    f.createBody({ shape: { type: 'box' } }),
    f.createBody({ shape: { type: 'sphere' } }),
    f.createJoint({ type: 'hinge', bodyA: null, bodyB: null, anchorA: [0, 0, 0] }),
    f.createJoint({ type: 'fixed', bodyA: null, bodyB: null, anchorA: [0, 0, 0] }),
    f.createJoint({ type: 'spring', bodyA: null, bodyB: null, anchorA: [0, 0, 0] }),
    f.createSoft('jelly'),
    f.createSoft('cloth'),
    f.createSoft('cable'),
    f.createSoft('balloon'),
    f.createGroup(),
    f.createLight('point'),
    f.createLight('spot'),
    f.createLight('directional'),
    f.createLight('area'),
    f.createPath(),
    ...MATERIAL_PRESETS.map((p) => f.createBody({ shape: { type: 'box' }, material: p.id })),
  ];
  const doc = f.newDocument('x');
  doc.entities = ents;
  // through the sanitiser, so the defaults are exactly what a loaded document has
  const clean = parseDocument(serializeDocument(doc));
  const entities = clean.entities.map((e) => {
    const c = { ...e } as Record<string, unknown>;
    delete c.id;
    delete c.name;
    return c;
  });
  const components: Record<string, unknown> = {};
  for (const def of listComponents()) {
    const { id, ...rest } = makeComponent(def.type);
    void id;
    components[def.type] = rest;
  }
  writeFileSync(
    'src/app/share/defaults.ts',
    `// GENERATED by tests/genShareDefaults.test.ts — snapshot of the document defaults (and one body per material preset)\n// that share format v2 is diffed against (DT-20). Do not edit by hand.\nimport type { Json } from './binary';\n\nexport const DEFAULT_SETTINGS: Json = ${JSON.stringify(clean.settings)};\n\nexport const DEFAULT_ENTITIES: Json[] = ${JSON.stringify(entities)};\n\n/** Default component (enabled + params) per component type registered when this file was generated. */\nexport const DEFAULT_COMPONENTS: Record<string, Json> = ${JSON.stringify(components)};\n`,
  );
});
