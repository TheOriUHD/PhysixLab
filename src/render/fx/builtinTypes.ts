/** Register the built-in types (once). Safe to call from every `Fx` constructor. */
export function registerBuiltinParticleTypes(): void {
  if (done) return;
  done = true;
  for (const t of BUILTIN_PARTICLE_TYPES) if (!particleTypes.has(t.id)) registerParticleType(t);
}
