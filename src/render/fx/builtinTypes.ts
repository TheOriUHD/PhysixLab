/**
 * The built-in particle types. Anyone can emit them by id (`fx.emit('spark', position)`); `fx.types()` lists them.
 *
 *   spark, spark.hot        additive streaks: impact sparks, explosion embers
 *   dust, dust.trail        soft earthy puffs (tinted by the surface colour)
 *   smoke, smoke.tyre, smoke.dark   rising, growing, drifting puffs
 *   chip.wood, chip.stone, shard.glass, shard.ice, scuff.rubber, crumb.foam   small material fragments
 *   glint                   a twinkle on a glass shard
 *   debris                  larger chunks from hard hits on brittle materials (bounce, settle, fade)
 *   blast.flash, blast.fire, blast.ring, blast.ringFlat, blast.dust    parts of an explosion
 *   glow                    a soft additive burst (muzzle / impact flash)
 *
 * Colours are sRGB; the intensity (third number of a stop) above 1 makes an additive particle glow past white.
 */
import { particleTypes, registerParticleType, type ParticleTypeDef } from './particleTypes';

type Defaults = Required<
  Pick<ParticleTypeDef, 'inherit' | 'stretch' | 'swirl' | 'floorFriction' | 'settle' | 'softFloor' | 'radius'>
>;

const base: Defaults = {
  inherit: 0,
  stretch: 0,
  swirl: 0,
  floorFriction: 0.6,
  settle: false,
  softFloor: false,
  radius: 0.03,
};

function type(d: Omit<ParticleTypeDef, keyof Defaults> & Partial<Defaults>): ParticleTypeDef {
  return { ...base, ...d };
}

