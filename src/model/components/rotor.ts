    if (owner.kind === 'joint') return owner.type !== 'hinge' ? 'A rotor on a joint needs a hinge.' : null;
    if (owner.bodyType !== 'dynamic') return 'Lift only moves dynamic bodies. Set the body type to Dynamic.';
